using System;
using System.Collections.Generic;
using System.Linq;
using Newtonsoft.Json;
using OneMoreBonk.Rebuild;
using UnityEngine;

public static class EconomyChecks
{
    static int assertions;
    static void Check(bool condition, string message)
    {
        assertions++;
        if (!condition) throw new Exception("Economy check: " + message);
    }
    static RiskForgeContext Context(params string[] ids) => new RiskForgeContext { Relics=ids.ToList() };
    static void Reject(Action action, string label)
    {
        bool rejected=false;
        try { action(); } catch (ArgumentException) { rejected=true; }
        Check(rejected,label);
    }

    // Literal observations from the researched site tables, not regenerated by the functions under test.
    // day, quota, basic price, special grade, special price, ward, rewind, chalk, powder, star, oblivion, delivery
    static readonly double[,] MerchantRows = {
        {3,2600,1040,0,2960,1100,3980,-1,-1,-1,-1,-1},
        {6,5700,2280,0,6490,2400,8730,3200,5130,3990,-1,5190},
        {9,12800,5120,2,23300,5380,19590,7170,11520,8960,27650,11650},
        {12,27750,11100,2,50510,11660,42460,15540,24980,19430,59940,25260},
        {15,58650,23460,4,160120,24640,89740,32850,52790,41060,126690,53380},
        {18,119350,47740,4,325830,50130,182610,66840,107420,83550,257800,108610},
        {21,232000,92800,4,633360,97440,354960,129920,208800,162400,501120,211120},
        {24,400896,160360,4,1094450,168380,613380,224510,360810,280630,865940,364820},
        {27,692748,277100,4,1891210,290960,1059910,387940,623480,484930,1496340,630410},
        {30,1197069,478830,4,3268000,502770,1831520,670360,1077370,837950,2585670,1089340}
    };

    public static int Run()
    {
        assertions=0;
        double[] quotas={1800,2100,2600,3350,4350,5700,7500,9800,12800,16700,21500,27750,35700,45800,58650,74650,94550,119350,149950,186850,232000};
        for(int i=0;i<quotas.Length;i++) Check(RiskEconomy.BaseQuotaForRound(i+1)==quotas[i],"original quota " +(i+1));
        Check(RiskEconomy.BaseQuotaForRound(22)==278400,"first extended quota");
        string[] itemIds={"ward","rewind","chalk","powder","starshard","oblivion","delivery"};
        for(int row=0;row<MerchantRows.GetLength(0);row++)
        {
            int round=(int)MerchantRows[row,0];double quota=RiskEconomy.BaseQuotaForRound(round);
            Check(quota==MerchantRows[row,1],"quoted merchant day quota " +round);
            Check(RiskEconomy.BasicSwordFirstPrice(quota)==MerchantRows[row,2],"basic sword price " +round);
            int grade=RiskEconomy.SpecialSwordGrade(round);
            Check(grade==MerchantRows[row,3] && RiskEconomy.SpecialSwordFirstPrice(quota,grade)==MerchantRows[row,4],"special sword price/grade " +round);
            for(int item=0;item<itemIds.Length;item++) if(MerchantRows[row,item+5]>=0)
            {
                double expected=MerchantRows[row,item+5];
                Check(RiskEconomy.MerchantItemFirstPrice(itemIds[item],quota)==expected,"item quote " +round+" "+itemIds[item]);
                Check(RiskEconomy.MerchantPrice(expected,1)==expected*3,"repeat price " +round+" "+itemIds[item]);
            }
        }
        Check(RiskEconomy.BasicSwordStock(3,false)==2 && RiskEconomy.BasicSwordStock(9,false)==3 && RiskEconomy.BasicSwordStock(12,false)==4 && RiskEconomy.BasicSwordStock(24,true)==7,"stock progression/writ");
        Check(RiskEconomy.MerchantOfferSlots(3,false)==4 && RiskEconomy.MerchantOfferSlots(6,false)==5 && RiskEconomy.MerchantOfferSlots(15,true)==8,"merchant offer budget");
        Check(RiskEconomy.OriginalMerchantItems().Length==7 && RiskEconomy.OriginalMerchantItems().Count(x=>x.EnabledInRebuild)==6,"original catalogue/deferred rewind");
        Check(!RiskEconomy.IsSupportedMerchantItem("rewind") && !RiskEconomy.IsSupportedMerchantItem("restore") && !RiskEconomy.IsSupportedMerchantItem("oil"),"no deferred or added recovery offered");
        Check(RiskEconomy.RerollPrice(1800,0)==270 && RiskEconomy.RerollPrice(1800,1)==675 && RiskEconomy.RerollPrice(1800,2)==1688,"reroll progression and ceil");
        Check(RiskEconomy.EffectiveQuota(1800,true,10000)==1134,"rebate then 30-percent cap");
        Check(RiskEconomy.Money(1.5)==2 && RiskEconomy.AddMoney(.25,.25)==1 && RiskEconomy.AddMoney(1e100,1e100)==1e100,"rounding/saturation");
        Reject(()=>RiskEconomy.BaseQuotaForRound(0),"invalid round");
        Reject(()=>RiskEconomy.MerchantPrice(100,-1),"negative purchase count");
        Reject(()=>RiskEconomy.Money(double.NaN),"NaN money");
        Reject(()=>RiskEconomy.Money(-1),"negative money");
        Reject(()=>RiskEconomy.SpecialSwordFirstPrice(1800,1),"invalid special grade");

        var empty=Context();var unchanged=JsonUtility.ToJson(empty);
        var miss=RiskEconomy.EvaluateTribute(21,0,0,232000,0,empty);
        Check(!miss.Passed && miss.AngerAfter==1 && miss.ContractCleared && !miss.Failed,"21st survivable underpayment clears");
        var fatal=RiskEconomy.EvaluateTribute(21,2,0,232000,0,empty);
        Check(fatal.Failed && !fatal.ContractCleared && fatal.AngerAfter==3,"third miss fails before clearing");
        var pardon=RiskEconomy.EvaluateTribute(21,2,0,232000,0,Context("dragonpardon"));
        Check(pardon.PardonConsumed && pardon.AngerAfter==2 && pardon.ContractCleared,"pardon protects third miss at ending");
        var tribute=RiskEconomy.EvaluateTribute(22,2,3000,1000,20,Context("collector","royalchange","testament","badge"));
        Check(tribute.Passed && tribute.AngerAfter==2 && tribute.GoldPaid==3000,"success pays full value and does not remove anger");
        Check(tribute.SwordCreditsGain==1 && tribute.ExtendedPaymentsGain==1 && tribute.NextRoyalCredit==600,"collector/excess/extended payment");
        Check(tribute.NextMinimumGrade==2 && tribute.NextFirstGrade==6,"badge/testament supply");
        var life=RiskEconomy.EvaluateTribute(3,0,1,1000,0,Context("lifecontract","mourning"));
        Check(life.NextMinimumGrade==7 && life.MourningGreatTicketsGain==1,"life contract applies after miss; mourning only on miss");
        var supplyContext=Context("supply","lifecontract");supplyContext.NextSupply=2;
        var supply=RiskEconomy.SupplyForNextRound(supplyContext,2,6);
        Check(supply.Count==6 && supply.MinimumGrade==7 && supply.FirstGrade==7 && supplyContext.NextSupply==2,"supply maximums and caller-owned consumption");
        Check(JsonUtility.ToJson(empty)==unchanged,"tribute calculations do not mutate context");
        var blank=RiskForgeRules.NewSword(1,17);
        Check(RiskEconomy.SwordCreditsForTrade(blank,Context("hook"),true,false)==2,"hook first untouched trade");
        blank.Hits=1;
        Check(RiskEconomy.SwordCreditsForTrade(blank,Context("hook"),true,false)==1,"hook does not reward hammered blank");

        var starters=new HashSet<string>();bool sawOblivion=false;
        for(uint seed=1;seed<=128;seed++)
        {
            uint firstSeed=seed,secondSeed=seed;
            var first=RiskEconomy.GenerateRelicOffers(1,new string[0],new string[0],ref firstSeed);
            var second=RiskEconomy.GenerateRelicOffers(1,new string[0],new string[0],ref secondSeed);
            Check(first.Count==3 && first.Distinct().Count()==3 && first.SequenceEqual(second) && firstSeed==secondSeed,"deterministic 3-of-8 starter draw");
            foreach(string id in first) { Check(RiskEconomy.StarterPool().Contains(id),"starter membership");starters.Add(id); }
            for(int round=2;round<=30;round++)
            {
                uint rng=seed;var offers=RiskEconomy.GenerateRelicOffers(round,new string[0],new[]{"nail"},ref rng);
                Check(offers.Count<=3 && offers.Distinct().Count()==offers.Count && !offers.Contains("nail"),"paid offer uniqueness/ownership");
                Check(offers.All(id=>{var e=RiskRelicData.Find(id);return !e.Disabled && e.FirstDay<=round && string.IsNullOrEmpty(e.Unlock);}),"paid offer availability/unlock gate");
            }
            uint merchantSeed=seed;var merchant=RiskEconomy.GenerateMerchantOffers(3,0,false,empty,ref merchantSeed);
            Check(merchant.Count==3 && merchant.Any(x=>x.Id=="ward") && merchant.All(x=>x.Id!="rewind" && x.Id!="restore"),"day3 explicit missing rewind, no substitution");
            Check(merchant.Where(x=>x.Kind=="sword").All(x=>x.RequiresEmptyHands),"physical hand source metadata");
            foreach(int anger in new[]{0,1})
            {
                merchantSeed=seed;merchant=RiskEconomy.GenerateMerchantOffers(30,anger,false,empty,ref merchantSeed);
                Check(merchant.Select(x=>x.Id).Distinct().Count()==merchant.Count && merchant.Count<=6,"merchant uniqueness/offer budget");
                Check(merchant.All(x=>x.Kind=="sword" || RiskEconomy.IsSupportedMerchantItem(x.Id)),"merchant excludes unsupported tools");
                if(anger==0)Check(!merchant.Any(x=>x.Id=="oblivion"),"oblivion anger gate");
                else sawOblivion|=merchant.Any(x=>x.Id=="oblivion");
            }
            merchantSeed=seed;merchant=RiskEconomy.GenerateMerchantOffers(30,1,true,empty,ref merchantSeed);
            Check(!merchant.Any(x=>x.Id=="oblivion"),"oblivion once-per-contract gate");
        }
        Check(starters.Count==8 && starters.Contains("shard") && !starters.Contains("loop"),"corrected random starter coverage");
        Check(sawOblivion,"eligible oblivion can appear; this is not a probability calibration");
        uint untouchedRng=7;var noVisit=RiskEconomy.GenerateMerchantOffers(2,0,false,empty,ref untouchedRng);
        Check(noVisit.Count==0 && untouchedRng==7,"nonvisit does not consume shop RNG");
        uint depletedRng=7;
        Check(RiskEconomy.GenerateRelicOffers(30,new string[0],RiskRelicData.All.Select(x=>x.Id),ref depletedRng).Count==0,"depleted shop terminates");

        var profile=new RiskProfile();var run=new RiskRun();
        Check(profile.UnlockedRelicSlots==2 && new RiskState().RuleId=="minimal-v1", "minimal profile/state defaults");
        Check(RiskProgression.Achievements().Length==19 && RiskProgression.Families().Length==9,"original achievement/family counts");
        foreach(var family in RiskProgression.Families())
        {
            var sword=RiskForgeRules.NewSword(1,17,"ordinary",19);sword.SourceFamily=family.Id;sword.PeakGrade=20;
            RiskProgression.ObserveSword(profile,run,sword);
            Check(!profile.Achievements.Contains(family.AchievementId),"family threshold not peak-only");
            sword.Grade=sword.PeakGrade=20;RiskProgression.ObserveSword(profile,run,sword);
            Check(profile.Achievements.Contains(family.AchievementId) && profile.UnlockedRelics.Contains(family.UnlockedRelicId),"family mastery unlock");
        }
        var fixtureSword=RiskForgeRules.NewSword(1,1,"ordinary",99);fixtureSword.IsFixture=true;
        RiskProgression.ObserveSword(profile,run,fixtureSword);
        Check(profile.Best==20 && !profile.Achievements.Any(x=>x.StartsWith("MOBILE_",StringComparison.Ordinal)),"no fixture/mobile progression reward");
        run.RealBrokenSwords=9;RiskProgression.ObserveBreak(profile,run);Check(!profile.Achievements.Contains("FORGE_BROKEN10"),"actual break threshold");
        run.RealBrokenSwords=10;RiskProgression.ObserveBreak(profile,run);Check(profile.UnlockedRelics.Contains("butterfingers") && run.RealBrokenSwords==10,"break observe does not double count");
        run.RealFrenzies=1;RiskProgression.ObserveFrenzy(profile,run);Check(profile.Achievements.Contains("FORGE_FIRSTFRENZY"),"first frenzy");
        run.RealFrenzies=5;RiskProgression.ObserveFrenzy(profile,run);Check(profile.UnlockedRelics.Contains("everwick") && run.RealFrenzies==5,"frenzy five");
        run.Round=22;run.ExtendedPayments=3;RiskProgression.ObserveTribute(profile,run,tribute,3000,1000,2);
        Check(profile.UnlockedRelics.Contains("lifecontract") && profile.UnlockedRelics.Contains("dragonpardon") && profile.UnlockedRelics.Contains("royalchange"),"tribute unlocks");
        run.Round=21;RiskProgression.ObserveTribute(profile,run,miss,0,232000,0);
        Check(profile.Achievements.Contains("FORGE_CLEAR") && profile.Completed==0,"survivable underpay clear observes without double counting completed contracts");
        var stocks=new[]{new RiskMerchantOffer { Stock=2,Purchased=1 }};
        Check(!RiskProgression.IsMerchantSoldOut(stocks),"all basic quantities required");stocks[0].Purchased=2;
        Check(RiskProgression.IsMerchantSoldOut(stocks) && !RiskProgression.IsMerchantSoldOut(new RiskMerchantOffer[0]),"soldout requires nonempty fully bought stock");
        RiskProgression.ObserveSoldOut(profile);RiskProgression.ObserveDeath(profile);
        foreach(var achievement in RiskProgression.Achievements()) { RiskProgression.Award(profile,achievement.Id);RiskProgression.Award(profile,achievement.Id); }
        Check(profile.Achievements.Count==19 && profile.UnlockedRelics.Count==16,"idempotent original nineteen/sixteen permanent unlocks");
        Reject(()=>RiskProgression.Award(profile,"MOBILE_FORGE99"),"unknown added achievement rejected");
        var state=new RiskState { Profile=profile,Run=run };run.MerchantOffers.Add(new RiskMerchantOffer { Id="ward",Stock=3,FirstPrice=1100,Purchased=1 });
        run.PendingBreak=new RiskPendingBreak { EventId=7,SwordId=1,PreSword=RiskForgeRules.NewSword(1,1),PostSword=RiskForgeRules.NewSword(1,1),PostContext=Context("repair"),Result=new RiskStrikeResult { Accepted=true,Fatal=true } };
        RiskState roundTrip=JsonUtility.FromJson<RiskState>(JsonUtility.ToJson(state));
        Check(roundTrip.Profile.Achievements.Count==19 && roundTrip.Run.MerchantOffers[0].Price==3300 && roundTrip.Run.PendingBreak.EventId==7,"field-only DTO headless serialization");
        Check(!typeof(RiskRun).GetFields().Any(x=>x.Name.Contains("Career") || x.Name.Contains("Side") || x.Name.Contains("Reservation") || x.Name.Contains("AdRestores")),"no legacy systems in new run DTO");
        return assertions;
    }

#if ECONOMY_CHECKS_STANDALONE
    public static int Main(string[] args)
    {
        try
        {
            if(args.Length!=1)throw new ArgumentException("Usage: economy.exe <resources-root>");
            Resources.Root=args[0];int count=Run();
            Console.WriteLine(JsonConvert.SerializeObject(new { status="PASS",economy_assertions=count,merchant_price_days=10,original_achievements=19,permanent_relic_unlocks=16,
                scope="Local pure economy and original-fact regression; not full Session, Steam executable, ads, native save or balance proof." }));
            return 0;
        }
        catch(Exception exception) { Console.Error.WriteLine(exception.ToString());return 1; }
    }
#endif
}
